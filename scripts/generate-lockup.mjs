/**
 * Turns the two words of the home lockup into SVG outlines, so GSAP's
 * DrawSVGPlugin can draw them on stroke by stroke. A webfont gives the
 * browser no glyph paths to animate — these have to be generated ahead of
 * time and committed.
 *
 * It is a one-off: run it again only if the text or either face changes.
 *
 *   npm i --no-save opentype.js
 *   # the two .ttf files come from the Google Fonts CSS API, asked for with
 *   # an old User-Agent so it serves TrueType rather than woff2:
 *   #   curl -A "Mozilla/4.0" "https://fonts.googleapis.com/css2?family=Rochester&family=Aboreto"
 *   node scripts/generate-lockup.mjs <rochester.ttf> <aboreto.ttf> > lib/lockup.ts
 */

import fs from "node:fs";
import opentype from "opentype.js";

const [scriptFace, capsFace] = process.argv.slice(2);
if (!scriptFace || !capsFace) {
  console.error("usage: generate-lockup.mjs <script.ttf> <caps.ttf>");
  process.exit(1);
}

const SIZE = 1000;

/**
 * The pen stroke for one glyph: a single arc from the baseline on the left,
 * over the top of the letter, back down to the baseline on the right. Stroked
 * thickly with a round cap it covers the whole glyph, so animating it with
 * DrawSVG as a mask uncovers the letter the way a pen lays it down — rather
 * than tracing its outline, which reads as tracing, not writing.
 */
function penStroke(box) {
  const w = box.x2 - box.x1;
  const h = box.y2 - box.y1;
  const cx = (box.x1 + box.x2) / 2;
  const foot = box.y2 - h * 0.14;
  const r = (n) => Math.round(n * 100) / 100;
  return {
    d: `M ${r(box.x1 - w * 0.06)} ${r(foot)} Q ${r(cx)} ${r(box.y1 - h * 0.12)} ${r(box.x2 + w * 0.06)} ${r(foot)}`,
    // Wide enough that the round brush covers the letter either side of the
    // arc; the mask also fades in a full cover at the end of each letter, so
    // nothing can be left behind.
    width: r(Math.max(h * 0.72, w * 0.9)),
  };
}

/** One entry per glyph, plus the box that holds them all. */
function outline(fontPath, text, letterSpacing) {
  const font = opentype.parse(fs.readFileSync(fontPath).buffer);
  const paths = font
    .getPaths(text, 0, 0, SIZE, { kerning: true, letterSpacing })
    .filter((path) => path.commands.length);

  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;
  for (const path of paths) {
    const box = path.getBoundingBox();
    minX = Math.min(minX, box.x1);
    minY = Math.min(minY, box.y1);
    maxX = Math.max(maxX, box.x2);
    maxY = Math.max(maxY, box.y2);
  }

  // A little air so the stroke is not clipped by the viewBox.
  const pad = SIZE * 0.02;
  minX -= pad;
  minY -= pad;
  maxX += pad;
  maxY += pad;

  return {
    viewBox: [minX, minY, maxX - minX, maxY - minY]
      .map((n) => Math.round(n * 100) / 100)
      .join(" "),
    glyphs: paths.map((path) => ({
      d: path.toPathData(2),
      pen: penStroke(path.getBoundingBox()),
    })),
  };
}

const signature = outline(scriptFace, "Aniketnaik", 0);
// The tracking matches the CSS the DOM fallback is set in.
const wordmark = outline(capsFace, "PORTFOLIO", 0.3);

const stringify = (value) => JSON.stringify(value, null, 2);

process.stdout.write(`// Generated by scripts/generate-lockup.mjs — do not edit by hand.
// The home lockup as outlines, one path per glyph, so DrawSVGPlugin has
// something to draw. Coordinates are font units at a 1000px em.

export type Glyph = {
  /** The filled letterform. */
  d: string;
  /** The stroke a pen would lay down to produce it, and how wide that pen is. */
  pen: { d: string; width: number };
};

export type Lockup = {
  viewBox: string;
  /** One glyph per letter, in writing order. */
  glyphs: Glyph[];
};

/** "Aniketnaik", in Rochester. */
export const SIGNATURE: Lockup = ${stringify(signature)};

/** "PORTFOLIO", in Aboreto, tracked to match the CSS fallback. */
export const WORDMARK: Lockup = ${stringify(wordmark)};
`);
